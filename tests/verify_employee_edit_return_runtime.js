const assert=require("assert");
const fs=require("fs");
const vm=require("vm");
const path=require("path");
const source=fs.readFileSync(path.join(__dirname,"../hrms/public/js/erpnext/employee.js"),"utf8");
const handlers={};
let route=["Form","Employee","EMP-1"];
const routes=[];
let onRouteChange;
const context=vm.createContext({window:{},__:(s)=>s,setTimeout:()=>{},frappe:{router:{on:(event,callback)=>onRouteChange=callback},ui:{form:{on:(name,events)=>handlers[name]=events}},get_route:()=>route,set_route:(...args)=>routes.push(args)}});
vm.runInContext(source,context);
const nav=context.window.hrmsEmployeeNavigation;
const frm={is_new:()=>false,doc:{name:"EMP-1"}};
nav.openEmployeeFormForEdit("EMP-1");
assert.deepStrictEqual(routes.pop(),["Form","Employee","EMP-1"]);
assert.strictEqual(nav.returnAfterEdit,"EMP-1");
assert.strictEqual(context.return_to_employee_detail_after_edit({is_new:()=>false,doc:{name:"EMP-2"}}),false);
route=["List","Employee"];
assert.strictEqual(context.return_to_employee_detail_after_edit(frm),false,"Never navigate away after user has left the editor");
route=["Form","Employee","EMP-1"];
assert.strictEqual(context.return_to_employee_detail_after_edit(frm),true);
assert.deepStrictEqual(routes.pop(),["employee-detail","EMP-1"]);
assert.strictEqual(nav.returnAfterEdit,undefined);
assert.strictEqual(context.return_to_employee_detail_after_edit(frm),false,"Normal form saves must not redirect");
nav.returnAfterEdit="EMP-1";
assert.strictEqual(context.return_to_employee_detail_after_edit({is_new:()=>true,doc:{name:"EMP-1"}}),false,"New employees keep roster return behavior");
assert(source.includes("if (!return_to_employee_detail_after_edit(frm)) return_to_employee_roster_after_insert(frm);"));
route=["List","Employee"];
onRouteChange();
assert.strictEqual(nav.returnAfterEdit,undefined,"Leaving the editor cancels an abandoned return target");
context.setup_employee_work_nature_field=()=>{};
context.sync_employee_work_nature_dependent_fields=()=>{};
let rosterReturns=0;
context.return_to_employee_roster_after_insert=()=>{rosterReturns++;};
route=["Form","Employee","EMP-1"];
nav.returnAfterEdit="EMP-1";
handlers.Employee.after_save(frm);
assert.deepStrictEqual(routes.pop(),["employee-detail","EMP-1"]);
assert.strictEqual(rosterReturns,0);
handlers.Employee.after_save(frm);
assert.strictEqual(rosterReturns,1);
console.log("Employee edit return: matching successful saves return to detail; unrelated and new records do not redirect.");
