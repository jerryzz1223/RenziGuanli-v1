const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'hrms/hr/page/recruitment_center/recruitment_center.js'), 'utf8');
const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const context = vm.createContext({ frappe: { pages: { 'recruitment-center': {} }, utils: { escape_html: escape } }, window: { addEventListener() {} } });
vm.runInContext(`${source}\nthis.Center = RecruitmentCenter;`, context);
const nodes = new Map();
const wrapper = { querySelector(selector) { if (!nodes.has(selector)) nodes.set(selector, { addEventListener() {} }); return nodes.get(selector); }, querySelectorAll() { return []; } };
const center = new context.Center({ main: [wrapper] });
assert.equal(center.register_view, 'list');
const record = { name: 'IR-EXAMPLE', candidate_name: '<script>unsafe</script>', hired: '是', age: 0 };
let html = center.render_daily_rows([record]);
assert.match(html, /已录用/);
assert.match(html, /未填写/);
assert.doesNotMatch(html, />待报到</, 'An empty arrival status must not become a confirmed workflow state');
assert.match(html, /&lt;script&gt;/);
assert.doesNotMatch(html, /<script>/);
center.register_view = 'template';
center.render_register_rows({ rows: [record] });
html = nodes.get('[data-register-results]').innerHTML;
assert.match(html, /<td>0<\/td>/, 'Zero age must remain visible');
assert.match(html, /<td>—<\/td>/);
assert.match(html, /已录用/);
assert.match(html, /&lt;script&gt;/);
const schema = JSON.parse(fs.readFileSync(path.join(root, 'hrms/hr/doctype/interview_registration/interview_registration.json'), 'utf8'));
assert.equal(new Set(schema.field_order).size, schema.field_order.length);
for (const key of schema.field_order) assert(schema.fields.some(field => field.fieldname === key), key);
let summary = '';
const layout = { length: 1, find() { return { remove() {} }; }, prepend(html) { summary = html; } };
const formContext = vm.createContext({ frappe: { ui: { form: { on() {} } }, utils: { escape_html: escape } } });
vm.runInContext(fs.readFileSync(path.join(root, 'hrms/hr/doctype/interview_registration/interview_registration.js'), 'utf8'), formContext);
formContext.render_interview_registration_summary({ doc: record, $wrapper: { find() { return layout; } } });
assert.match(summary, /报到：未填写/);
assert.match(summary, /&lt;script&gt;/);
console.log('Interview list defaults, truthful states, escaping, full-field values and form summary passed.');
